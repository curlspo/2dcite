export const US_STATE_CODES: readonly string[] = US_STATES.map((s) => s.code);

const codeSet = new Set<string>(US_STATE_CODES);

export function isUsStateCode(value: string): boolean {
  return codeSet.has(value.toUpperCase().trim());
}

export function normalizeUsStateCode(value: string): string | null {
  const code = value.toUpperCase().trim();
  return codeSet.has(code) ? code : null;
}
